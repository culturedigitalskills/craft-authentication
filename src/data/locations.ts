/**
 * The country's name in the visitor's language, falling back to the stored
 * English name where the browser has no translation.
 */
export function countryLabel(country: Country, locale: string): string {
    if (locale === 'en') return country.name
    try {
        let names = displayNames.get(locale)
        if (!names) {
            names = new Intl.DisplayNames([locale], { type: 'region', fallback: 'none' })
            displayNames.set(locale, names)
        }
        return names.of(country.isoCode) ?? country.name
    } catch {
        return country.name
    }
}

const displayNames = new Map<string, Intl.DisplayNames>()
